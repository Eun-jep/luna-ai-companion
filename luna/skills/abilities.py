"""«Что ты умеешь?» / "what can you do?" / "뭘 할 수 있어?" / "何ができるの?": the program knows exactly what she can do right now (which switches are on) and hands her
a true list, so that she neither boasts of what she cannot do nor forgets what she can. She retells it in her own words and picks what fits him, not a brochure."""
import re

_ASK = re.compile(r'(?i)что (?:ты |вы )?(?:умеешь|можешь|ещё умеешь|еще умеешь)|на что ты способна|какие у тебя (?:навыки|умения|способности|возможности)|чем ты (?:можешь )?(?:помочь|полезна)|'
                  r'what (?:can|do) you (?:do|know how to do)|what are you (?:able|capable)|what.?s your skill|what are your (?:skills|abilities|features)|how can you help|'
                  r'뭘 (?:할 수 있|잘해)|뭐 (?:할 수 있|잘해)|무엇을 할 수 있|어떤 (?:걸|것을) (?:할 수|도와)|할 수 있는 (?:게|것)|'
                  r'何ができ|なにができ|どんなことができ|何が得意|できること')

ALWAYS = ('поговорить, поддержать и вспомнить то, что он ей рассказывал (память и привычки общения растут сами)',
          'говорить голосом и слушать его голос (если включён микрофон)',
          'ставить напоминания (пока Луна открыта), вести списки покупок и дел, привычки с сериями дней, подсказать, что у него на сегодня',
          'точно считать: арифметика, проценты, единицы, даты («сколько дней до…»), монетка, кубики, выбор из вариантов',
          'учить в режиме практики: языки и другие темы с разбором ошибок',
          'знать факты про десятки игровых движков и узнавать типичные ошибки движков по тексту',
          'подстроиться под его просьбы о манере: короче, подробнее, без шуток, по-английски, как называть')
ACTIONS = ('по его просьбе открыть программу или сайт, найти файл, поискать в интернете и посмотреть курс валют (каждый шаг с его подтверждением)',)
WORK = ('читать его код и проекты, предлагать правки блоком и применять их после его нажатия, запускать команды и тесты после его нажатия',
        'руками в Unreal, Unity и Godot: сцены, объекты, скрипты, запуск (каждая операция ждёт его нажатия), и готовые рецепты вроде платформера',
        'осмотреть папку проекта любого движка и рассказать, что в ней, только на чтение',
        'составить документ, таблицу или презентацию (создаются после его нажатия)')
LIMITS = ('не слышит и не видит его, пока он не включил микрофон или не показал ей экран',
          'не умеет писать первой «в нужный час», если Луна закрыта, и не обещает этого',
          'не вводит пароли, платежи и личные данные и не обходит капчи',
          'в движках кроме Unreal, Unity и Godot руками работать не умеет: читает, советует и пишет код блоком',
          'может ошибаться, и тогда честно скажет, а не выдумает')


def asked(text):
    return bool(_ASK.search(str(text or '')[:200]))


def hint(text, agent=False, work=False):
    """The true list for this moment, or '' when he did not ask what she can do."""
    if not asked(text):
        return ''
    can = list(ALWAYS)
    if agent:
        can += list(ACTIONS)
    if work and agent:
        can += list(WORK)
    off = []
    if not agent:
        off.append('«Действия» выключены: открывать программы и сайты, искать в интернете и смотреть курсы она сейчас не может, пока он не включит этот переключатель')
    if not (work and agent):
        off.append('рабочий режим выключен: код, команды, проекты и движки руками сейчас недоступны, пока он его не включит')
    return ('[Он спрашивает, что ты умеешь. Вот точный список на сейчас, ничего сверх него не обещай. Умеет: %s. Сейчас выключено: %s. Не умеет совсем: %s. '
            'Перескажи по-своему и коротко, выбери 3–4 вещи, самые полезные ему сейчас, остальное предложи рассказать, если захочет; без списков и канцелярита, и без хвастовства.]'
            % ('; '.join(can), '; '.join(off) if off else 'ничего', '; '.join(LIMITS)))
